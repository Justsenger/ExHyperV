export function syncWindowsToProcesses(
  baseList: TmProcessNode[],
  windows: readonly WindowInstance[],
  hw: VirtualHardwareSnapshot,
): TmProcessNode[] {
  const result = baseList.map((n) => ({
    ...n,
    children: n.children ? n.children.map((c) => ({ ...c })) : undefined,
  }));

  for (const w of windows) {
    if (w.appId === 'task-manager') continue;
    const id = `win-${w.pid}`;
    if (!result.some((r) => r.id === id)) {
      const manifest = getManifestById(w.appId);
      const mem = manifest?.telemetry?.estimatedMemMb ?? (w.appId === 'exhyperv' ? 188.5 : 64.0);
      const pub = manifest?.telemetry?.publisher ?? (w.appId === 'exhyperv' ? 'ExHyperV Project' : 'Microsoft Corporation');
      const cpu = w.appId === 'exhyperv' ? +(0.8 + (hw.cpu.usagePct % 3) * 0.4).toFixed(1) : 0.2;
      result.unshift({
        id,
        pid: w.pid,
        name: w.title,
        processName: `${w.appId}.exe`,
        commandLine: `"C:\\Program Files\\WindowsApps\\${w.appId}\\${w.appId}.exe"`,
        publisher: pub,
        group: 'app',
        status: w.minimized ? 'suspended' : '',
        cpu,
        memMb: mem,
        diskMbS: 0,
        netMbps: 0,
        gpuPct: w.minimized ? 0 : 0.6,
        gpuEngine: w.minimized ? '' : 'GPU 0 - 3D',
        npuPct: 0,
        npuEngine: '',
        powerUsage: cpu > 1 ? '中' : '极低',
        powerTrend: '极低',
        isolation: '无',
        arch: 'ARM64',
        user: 'admin',
        desc: manifest?.description ?? w.title,
        priority: '正常',
        appId: w.appId,
        iconKey: w.iconKey,
        filePath: `C:\\Program Files\\WindowsApps\\${w.appId}\\${w.appId}.exe`,
      });
    }
  }
  return result;
}

export function formatCpuTime(totalSec: number): string {
  const h = Math.floor(totalSec / 3600);
  const m = Math.floor((totalSec % 3600) / 60);
  const s = totalSec % 60;
  return `${h}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}`;
}

export function formatMemMb(mb: number, mode: TmResourceDisplayMode, totalMb: number): string {
  if (mode === 'percent') {
    const pct = totalMb > 0 ? (mb / totalMb) * 100 : 0;
    return `${pct.toFixed(1)}%`;
  }
  return `${mb.toFixed(1)} MB`;
}

export function formatMemKb(mb: number): string {
  const kb = Math.max(64, Math.round(mb * 1024));
  return `${kb.toLocaleString('en-US')} K`;
}

export function getHeatClass(ratio01: number): string {
  if (ratio01 >= 0.45) return 'is-heat-3';
  if (ratio01 >= 0.16) return 'is-heat-2';
  if (ratio01 >= 0.03) return 'is-heat-1';
  return 'is-heat-0';
}
